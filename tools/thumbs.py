"""Render a small thumbnail of every module and write src/thumbs.js.

Each module is drawn on the stand-in photograph (as a base, or as a layer over image A) after a
warm-up, then encoded as a tiny WebP. The picker shows them so modules can be chosen by sight.
Run after adding or changing a module:

    ./build.sh && python3 tools/thumbs.py && ./build.sh
"""
import base64, io, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / 'tests'))
from playwright.sync_api import sync_playwright
from PIL import Image
from helpers import launch, ROOT

W, H, TW, TH = 440, 550, 88, 110

JS = """([W, H]) => {
  const f = window.fxlab, E = f.Engine, S = f.state, D = f.Data;
  f.App.playing = false; f.App.exporting = true;
  S.W = W; S.H = H; E.setSize(W, H, .4);
  S.duration = 4; S.loopMode = 'pingpong'; S.easing = 'Linear'; S.hold = 0;
  D.clear();
  const out = {};
  for (const m of f.FX.modules){
    const role = CATS.find(c => c.id === m.cat).role;
    E.resetFeedback(S.stack);
    S.sources.A.process = []; S.sources.B.process = [];
    const inst = f.makeInst(m.id);
    if (role === 'base'){ S.base = inst; S.stack = []; } else { S.base = f.makeInst('src-a'); S.stack = [inst]; }
    const t = m.cat === 'transition' ? .8 : 1.4;
    for (let i = 30; i >= 0; i--) f.renderAt(t - i / 30);
    out[m.id] = E.canvas.toDataURL('image/png');
  }
  return out;
}"""


def main():
    with sync_playwright() as p:
        browser, page, errors = launch(p)
        shots = page.evaluate(JS, [W, H])
        browser.close()
    if errors:
        print('page errors:', errors[:3])
    rows, total = [], 0
    for mid, url in shots.items():
        im = Image.open(io.BytesIO(base64.b64decode(url.split(',', 1)[1]))).convert('RGB').resize((TW, TH), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, 'WEBP', quality=52, method=6)
        b64 = base64.b64encode(buf.getvalue()).decode()
        total += len(b64)
        rows.append(f"  '{mid}':'{b64}',")
    src = ("/* ---------------- Module thumbnails ----------------\n"
           "   Generated by tools/thumbs.py: each module on the stand-in photograph, 88×110 WebP.\n"
           "   Do not edit by hand. Rerun the tool after adding or changing a module.\n"
           "------------------------------------------------ */\n"
           "const THUMBS = {\n" + '\n'.join(rows) + "\n};\n"
           "const thumbSrc = id => THUMBS[id] ? 'data:image/webp;base64,' + THUMBS[id] : '';\n")
    (ROOT / 'src' / 'thumbs.js').write_text(src)
    print(f'ok    thumbs · {len(rows)} modules · {total // 1024} KB of base64 → src/thumbs.js')


if __name__ == '__main__':
    main()
